from __future__ import annotations

import re
import sqlite3
import time
from pathlib import Path
from typing import Any
from urllib.parse import quote


class SQLToolError(Exception):
    """Base SQL tool error."""


class SQLSecurityError(SQLToolError):
    """Unsafe or unauthorized SQL operation."""


class SQLExecutionError(SQLToolError):
    """SQL query execution failure."""


READ_ONLY_ACTIONS = {
    sqlite3.SQLITE_SELECT,
    sqlite3.SQLITE_READ,
    sqlite3.SQLITE_FUNCTION,
    sqlite3.SQLITE_RECURSIVE,
}

DENIED_FUNCTIONS = {
    "load_extension",
    "writefile",
    "readfile",
}


def validate_sql(sql: str) -> str:
    """Apply preliminary restrictions to SQL input."""
    if not isinstance(sql, str):
        raise SQLSecurityError("SQL must be a string.")

    sql = sql.strip()

    if not sql or len(sql) > 10000:
        raise SQLSecurityError("SQL is empty or too long.")

    # SQLite accepts only one statement in execute(), but
    # reject statement delimiters as additional defense.
    if ";" in sql:
        raise SQLSecurityError("Semicolons are not allowed.")

    # Block SQL comments to reduce parser ambiguity.
    if "--" in sql or "/*" in sql or "*/" in sql:
        raise SQLSecurityError("SQL comments are not allowed.")

    if not re.match(r"^(SELECT|WITH)\b", sql, re.IGNORECASE):
        raise SQLSecurityError(
            "Only SELECT and WITH SELECT queries are allowed."
        )

    return sql


def sqlite_readonly_authorizer(
    action: int,
    arg1: str | None,
    arg2: str | None,
    database: str | None,
    source: str | None,
) -> int:
    """Allow only approved SQLite operations."""
    if action not in READ_ONLY_ACTIONS:
        return sqlite3.SQLITE_DENY

    if action == sqlite3.SQLITE_FUNCTION:
        function_name = (arg2 or arg1 or "").lower()
        if function_name in DENIED_FUNCTIONS:
            return sqlite3.SQLITE_DENY

    return sqlite3.SQLITE_OK


class ReadOnlySQLTool:
    """Read-only SQLite query service for trusted analytics."""

    def __init__(
        self,
        database_path: str,
        max_rows: int = 500,
        timeout_seconds: float = 3.0,
    ) -> None:
        if (
            isinstance(max_rows, bool)
            or not isinstance(max_rows, int)
            or not 1 <= max_rows <= 10000
        ):
            raise SQLToolError("max_rows must be between 1 and 10000.")

        if (
            isinstance(timeout_seconds, bool)
            or not isinstance(timeout_seconds, (int, float))
            or not 0 < timeout_seconds <= 60
        ):
            raise SQLToolError("Invalid timeout_seconds.")

        path = Path(database_path).expanduser().resolve()

        if not path.is_file():
            raise SQLToolError("Database file does not exist.")

        self.database_path = path
        self.max_rows = max_rows
        self.timeout_seconds = float(timeout_seconds)

    def _connect(self) -> sqlite3.Connection:
        encoded = quote(str(self.database_path), safe="/:")
        uri = f"file:{encoded}?mode=ro"

        connection = sqlite3.connect(
            uri,
            uri=True,
            timeout=self.timeout_seconds,
        )
        connection.row_factory = sqlite3.Row

        # Avoid schema changes, writes and external DB access.
        connection.execute("PRAGMA query_only = ON")
        connection.set_authorizer(sqlite_readonly_authorizer)

        return connection

    def execute_query(
        self,
        sql: str,
        parameters: tuple[Any, ...] | dict[str, Any] = (),
    ) -> dict[str, Any]:
        """Execute a bounded, read-only SQL query."""
        sql = validate_sql(sql)

        if not isinstance(parameters, (tuple, dict)):
            raise SQLToolError(
                "Parameters must be a tuple or dictionary."
            )

        start = time.monotonic()
        connection = self._connect()

        def check_timeout() -> int:
            elapsed = time.monotonic() - start
            return int(elapsed > self.timeout_seconds)

        try:
            connection.set_progress_handler(
                check_timeout, 1000
            )

            cursor = connection.execute(sql, parameters)
            records = cursor.fetchmany(self.max_rows + 1)

            truncated = len(records) > self.max_rows
            records = records[:self.max_rows]

            columns = [
                column[0]
                for column in cursor.description or []
            ]

            rows = [
                dict(zip(columns, tuple(record)))
                for record in records
            ]

            return {
                "success": True,
                "columns": columns,
                "rows": rows,
                "row_count": len(rows),
                "truncated": truncated,
                "duration_ms": round(
                    (time.monotonic() - start) * 1000, 2
                ),
                "read_only": True,
            }

        except sqlite3.Error as exc:
            raise SQLExecutionError(
                f"Read-only query failed: {exc}"
            ) from exc

        finally:
            connection.close()

    def list_tables(self) -> list[str]:
        """List user-defined tables."""
        result = self.execute_query(
            "SELECT name FROM sqlite_master "
            "WHERE type = 'table' "
            "AND name NOT LIKE 'sqlite_%' "
            "ORDER BY name"
        )
        return [row["name"] for row in result["rows"]]

    def describe_table(
        self,
        table_name: str
    ) -> list[dict[str, Any]]:
        """Inspect columns through SQLite's table-valued PRAGMA."""
        if not isinstance(table_name, str) or not table_name:
            raise SQLToolError("table_name is required.")

        result = self.execute_query(
            "SELECT name, type, notnull, dflt_value, pk "
            "FROM pragma_table_info(?)",
            (table_name,),
        )
        return result["rows"]

    def count_rows(
        self,
        table_name: str
    ) -> int:
        """Count rows in a validated user-defined table."""
        if table_name not in self.list_tables():
            raise SQLSecurityError(
                "Unknown or unauthorized table."
            )

        # Identifiers cannot use SQL bind parameters.
        # Exact membership check above is mandatory.
        quoted_name = '"' + table_name.replace('"', '""') + '"'

        result = self.execute_query(
            f"SELECT COUNT(*) AS total FROM {quoted_name}"
        )
        return int(result["rows"][0]["total"])


def build_sales_summary_query(
    store_id: str | None = None
) -> tuple[str, tuple[Any, ...]]:
    """
    Generate a parameterized sales summary query.

    Expected schema:
        sales(
            store_id TEXT,
            product_id TEXT,
            quantity INTEGER,
            net_revenue REAL,
            cost_of_goods REAL
        )
    """
    sql = (
        "SELECT product_id, "
        "SUM(quantity) AS units_sold, "
        "ROUND(SUM(net_revenue), 2) AS revenue, "
        "ROUND(SUM(net_revenue - cost_of_goods), 2) "
        "AS gross_profit "
        "FROM sales"
    )

    params: tuple[Any, ...] = ()

    if store_id is not None:
        sql += " WHERE store_id = ?"
        params = (store_id,)

    sql += (
        " GROUP BY product_id "
        "ORDER BY revenue DESC "
        "LIMIT 100"
    )

    return sql, params


def build_inventory_risk_query(
    warehouse_id: str | None = None
) -> tuple[str, tuple[Any, ...]]:
    """
    Generate an inventory-risk query.

    Expected schema:
        inventory(
            warehouse_id TEXT,
            product_id TEXT,
            available_stock INTEGER,
            reorder_point INTEGER
        )
    """
    sql = (
        "SELECT product_id, warehouse_id, "
        "available_stock, reorder_point, "
        "(reorder_point - available_stock) AS shortage "
        "FROM inventory "
        "WHERE available_stock <= reorder_point"
    )

    params: tuple[Any, ...] = ()

    if warehouse_id is not None:
        sql += " AND warehouse_id = ?"
        params = (warehouse_id,)

    sql += " ORDER BY shortage DESC LIMIT 100"

    return sql, params


def execute_sql_tool(
    tool: ReadOnlySQLTool,
    action: str,
    arguments: dict[str, Any],
) -> dict[str, Any]:
    """Structured allowlisted SQL agent interface."""
    actions = {
        "execute_query": tool.execute_query,
        "list_tables": tool.list_tables,
        "describe_table": tool.describe_table,
        "count_rows": tool.count_rows,
    }

    if action not in actions:
        return {
            "success": False,
            "error": "Unknown SQL tool action."
        }

    if not isinstance(arguments, dict):
        return {
            "success": False,
            "error": "Arguments must be a dictionary."
        }

    try:
        return {
            "success": True,
            "action": action,
            "result": actions[action](**arguments),
        }
    except (SQLToolError, TypeError, ValueError) as exc:
        return {
            "success": False,
            "action": action,
            "error": str(exc),
        }


